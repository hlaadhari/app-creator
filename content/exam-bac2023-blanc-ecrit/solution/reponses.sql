UPDATE ANNONCE SET PrixVente = PrixVente * 0.9 WHERE ImmatVeh IN (SELECT ImmatVeh FROM VEHICULE WHERE PuisFisc >= 6);
DELETE FROM ANNONCE WHERE DateAnn < '2020-01-01';
DELETE FROM ANNONCE WHERE PrixVente = (SELECT MIN(PrixVente) FROM ANNONCE);
SELECT DISTINCT NomMod FROM MODELE M JOIN VEHICULE V ON M.IdMod = V.IdMod JOIN ANNONCE A ON V.ImmatVeh = A.ImmatVeh WHERE Energie = 'D' AND PrixVente <= 50000;
SELECT IdMod, COUNT(*) AS NbAnnonces FROM VEHICULE V JOIN ANNONCE A ON V.ImmatVeh = A.ImmatVeh GROUP BY IdMod;
SELECT IdVend, SUM(PrixVente) AS TotalVentes FROM ANNONCE GROUP BY IdVend;
